export const CLI_COMMANDS = COMMANDS.map((item) => ({
  ...DEFAULT_METADATA,
  ...item,
  readOnly: item.readOnly ?? (item.mutating ? false : DEFAULT_METADATA.readOnly)
}));

export function listCommandMetadata() {
  return [...CLI_COMMANDS].sort((a, b) => a.command.localeCompare(b.command));
}

export function findCommandMetadata(command) {
  return CLI_COMMANDS.find((item) => item.command === command) || null;
}

export function listInternalOnlyCommands() {
  return listCommandMetadata().filter((item) => item.internalOnly).map((item) => item.command);
}
